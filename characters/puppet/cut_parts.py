"""Slice the cut-out character into puppet parts with hidden joint fill. Coordinates are in source pixels."""
import json, sys
import numpy as np
from PIL import Image, ImageDraw, ImageFilter

src = Image.open(sys.argv[1]).convert("RGBA")
out_dir = sys.argv[2]
A = np.array(src).astype(np.float32)
H, W = A.shape[:2]
alpha = A[:, :, 3]
lum = A[:, :, :3] @ np.array([0.299, 0.587, 0.114])
Y, X = np.mgrid[0:H, 0:W]
fg = alpha > 8

def med(x0, y0, x1, y1):
    reg = A[y0:y1, x0:x1]; m = reg[:, :, 3] > 200
    return tuple(int(v) for v in np.median(reg[m][:, :3], axis=0))

SHIRT, SKIN_ARM, PANTS, NECK, LID = med(440, 760, 520, 840), med(190, 780, 215, 810), med(370, 1150, 410, 1250), med(455, 430, 495, 450), med(466, 252, 482, 266)

J = {  # joints (source px)
    "neck": (475, 425), "hips": (475, 1005),
    "shoulderR": (300, 505), "elbowR": (170, 845), "wristR": (122, 955),
    "shoulderL": (650, 505), "elbowL": (780, 845), "wristL": (828, 955),
    "hipR": (395, 1010), "kneeR": (385, 1350), "hipL": (555, 1010), "kneeL": (565, 1350),
}
def seamL(y): return np.where(y < 700, 285 + (y - 450) * 0.06, 296)   # drop-shoulder seams, then the shirt sides
def seamR(y): return np.where(y < 700, 665 - (y - 450) * 0.06, 654)

head = fg & ((Y < 410) | ((Y < 470) & (lum > 70) & (X > 380) & (X < 570)))
lower = fg & (Y >= 1130) | fg & (X > 295) & (X < 655) & (Y >= 990) & ~((Y < 1045) & (lum < 70))
armR = fg & ~head & ~lower & (X < seamL(Y) + 7 * (Y < 720)) & (Y > 430) & (Y < 1130)  # overlaps under the shirt edge
armL = fg & ~head & ~lower & (X > seamR(Y) - 7 * (Y < 720)) & (Y > 430) & (Y < 1130)
torso = fg & ~head & ~lower & (X >= seamL(Y)) & (X <= seamR(Y))

def side_of(p0, p1, through, slack=0):  # True where a pixel is past the cut perpendicular to p0->p1 at `through`
    d = np.array(p1, float) - np.array(p0, float); d /= np.linalg.norm(d)
    return ((X - through[0]) * d[0] + (Y - through[1]) * d[1]) > slack

masks = {
    "pelvis": lower & (Y < 1120),
    "head": head, "torso": torso,
    "upperArmR": armR & ~side_of(J["shoulderR"], J["wristR"], J["elbowR"], 8),
    "forearmR": armR & side_of(J["shoulderR"], J["wristR"], J["elbowR"]),
    "upperArmL": armL & ~side_of(J["shoulderL"], J["wristL"], J["elbowL"], 8),
    "forearmL": armL & side_of(J["shoulderL"], J["wristL"], J["elbowL"]),
    "thighR": lower & (X < 472) & (Y < J["kneeR"][1] + 8), "shinR": lower & (X < 472) & (Y >= J["kneeR"][1]),
    "thighL": lower & (X >= 472) & (Y < J["kneeL"][1] + 8), "shinL": lower & (X >= 472) & (Y >= J["kneeL"][1]),
}
fills = {  # hidden overlap fill drawn beneath each part: (kind, params, colour)
    "pelvis": [("rect", (330, 960, 620, 1100), PANTS)],
    "head": [("rect", (420, 400, 530, 500), NECK)],
    "upperArmR": [("disc", (*J["elbowR"], 29), SKIN_ARM)],
    "upperArmL": [("disc", (*J["elbowL"], 29), SKIN_ARM)],
    "thighR": [("rect", (330, 960, 462, 1032), PANTS), ("disc", (*J["kneeR"], 52), PANTS)],
    "thighL": [("rect", (482, 960, 620, 1032), PANTS), ("disc", (*J["kneeL"], 52), PANTS)],
}

meta = {"source_size": [W, H], "feet_y": int(np.where(fg.any(1))[0].max()), "joints": J, "parts": {},
        "eyes": {"R": [432, 262], "L": [515, 262], "size": [40, 25], "lid": LID, "mouth": [475, 332]}}
for name, m in masks.items():
    layer = Image.new("RGBA", (W, H))
    d = ImageDraw.Draw(layer)
    for kind, p, col in fills.get(name, []):
        if kind == "disc": d.ellipse((p[0] - p[2], p[1] - p[2], p[0] + p[2], p[1] + p[2]), fill=col + (255,))
        else: d.rectangle(p, fill=col + (255,))
    if fills.get(name): layer = layer.filter(ImageFilter.GaussianBlur(1.2))
    part = A.copy(); part[:, :, 3] = np.where(m, alpha, 0)
    layer.alpha_composite(Image.fromarray(part.astype(np.uint8)))
    bb = layer.getbbox()
    layer.crop(bb).save(f"{out_dir}/{name}.png", optimize=True)
    meta["parts"][name] = {"box": list(bb)}
open(f"{out_dir}/rig.js", "w").write("// generated by cut_parts.py from full.png — source-pixel boxes and joints\nexport const RIG = " + json.dumps(meta) + ";\n")
print({k: v["box"] for k, v in meta["parts"].items()})
print("colours", SHIRT, SKIN_ARM, PANTS, NECK, LID)
